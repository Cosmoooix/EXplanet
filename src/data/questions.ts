/**
 * Question bank helper to retrieve a random question ensuring no duplicates
 * until the whole filtered or available pool is exhausted.
 */
export function getRandomQuestion(
  answeredIds: string[],
  subjectFilter?: Subject | 'All',
  difficultyFilter?: Difficulty | 'All'
): { question: Question; isPoolReset: boolean } {
  let pool = QUESTIONS_DATABASE.filter(q => {
    if (subjectFilter && subjectFilter !== 'All' && q.subject !== subjectFilter) return false;
    if (difficultyFilter && difficultyFilter !== 'All' && q.difficulty !== difficultyFilter) return false;
    return true;
  });

  if (pool.length === 0) {
    // Fallback to all if overly restrictive
    pool = QUESTIONS_DATABASE;
  }

  // Filter out previously answered questions
  const unexhausted = pool.filter(q => !answeredIds.includes(q.id));

  let selected: Question;
  let isPoolReset = false;

  if (unexhausted.length > 0) {
    const randomIndex = Math.floor(Math.random() * unexhausted.length);
    selected = unexhausted[randomIndex];
  } else {
    // Pool exhausted! Reset and pick from full pool
    isPoolReset = true;
    const randomIndex = Math.floor(Math.random() * pool.length);
    selected = pool[randomIndex];
  }

  return { question: selected, isPoolReset };
}
