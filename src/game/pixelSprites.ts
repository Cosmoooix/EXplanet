/**
 * EXPlanet Procedural Pixel Art Sprite Generator.
 * Generates crisp retro 16x16 / 24x24 pixel art sprites directly onto canvas
 * with nearest-neighbor rendering (no external broken image assets).
 */

type ColorMap = Record<string, string>;

// Helper to draw a pixel matrix onto a canvas context at a given position and scale
export function drawPixelMatrix(
  ctx: CanvasRenderingContext2D,
  matrix: string[],
  colorMap: ColorMap,
  x: number,
  y: number,
  pixelSize: number = 2
) {
  for (let row = 0; row < matrix.length; row++) {
    const line = matrix[row];
    for (let col = 0; col < line.length; col++) {
      const char = line[col];
      if (char !== ' ' && colorMap[char]) {
        ctx.fillStyle = colorMap[char];
        ctx.fillRect(x + col * pixelSize, y + row * pixelSize, pixelSize, pixelSize);
      }
    }
  }
}

